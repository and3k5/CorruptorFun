# mkdata.py: turns duck.png into 15-bit VRAM pixels (duck.raw) and writes the
# tables the program uses (tables.h).
import math
from PIL import Image

im = Image.open('duck.png').convert('RGB')
assert im.size == (320, 240), im.size
# Ordered dither down to 5 bits per channel.
bayer = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
out = bytearray()
px = im.load()
for y in range(240):
    for x in range(320):
        r, g, b = px[x, y]
        d = (bayer[y & 3][x & 3] - 7.5) / 16 * 8
        q = [max(0, min(31, int((c + d) / 255 * 31 + 0.5))) for c in (r, g, b)]
        out += (q[0] | q[1] << 5 | q[2] << 10).to_bytes(2, 'little')
open('duck.raw', 'wb').write(out)

with open('tables.h', 'w') as f:
    f.write('// Generated by mkdata.py.\n')
    f.write('static const signed char sine[256] = {%s};\n' % ','.join(str(round(64 * math.sin(i * 2 * math.pi / 256))) for i in range(256)))
    cols = []
    for i in range(64):
        h = i / 64
        r, g, b = (round(255 * (0.5 + 0.5 * math.cos(2 * math.pi * (h + k / 3)))) for k in (0, 1, 2))
        cols.append('0x%02X%02X%02X' % (b, g, r))
    f.write('static const unsigned int rainbow[64] = {%s};\n' % ','.join(cols))
